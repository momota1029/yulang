#[cfg(test)]
mod tests {
    use super::Sha256;

    #[test]
    fn matches_known_sha256_vector() {
        let mut digest = Sha256::new();
        digest.update(b"a");
        digest.update(b"bc");
        assert_eq!(
            digest.finish(),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }
}
